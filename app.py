import pandas as pd
import string
from openai import OpenAI

# 1. ПОДКЛЮЧАЕМСЯ К СЕРВЕРУ LM STUDIO
client = OpenAI(base_url="http://localhost:1234/v1", api_key="lm-studio")

# 2. ЗАГРУЖАЕМ ЛОКАЛЬНЫЙ ДАТАСЕТ ТОНАЛЬНОСТИ (Твои плохие слова)
negative_words = set()
try:
    df = pd.read_csv('kartaslovsent.csv', sep=';', encoding='utf-8')
    for _, row in df.iterrows():
        term = str(row.get('term', '')).strip().lower()
        tag = str(row.get('tag', '')).strip().upper()
        if term and term != 'nan' and tag == 'NGTV':
            negative_words.add(term)
    print("✓ Локальный файл тональности успешно загружен!")
except Exception as e:
    print(f"❌ Ошибка загрузки файла тональности: {e}")

# 3. ФУНКЦИЯ ПРОВЕРКИ ВЕЖЛИВОСТИ
def is_polite(text):
    # Приводим к нижнему регистру и убираем лишние пробелы по краям
    cleaned_text = text.lower().strip()
    
    # 1. ПЕРВЫЙ ЭТАП: Жесткий фильтр опасных устойчивых фраз и выкриков (подстрок)
    text_without_spaces = cleaned_text.replace(' ', '')
    hard_ban_phrases = [
        'идинахуй', 'пошелнахуй', 'нахуй', 'сука', 
        'бля', 'блять', 'блядь', 'хуй', 'пиздец'
    ] 
    
    for phrase in hard_ban_phrases:
        if phrase in text_without_spaces:
            return False  # Мгновенный бан, если кусок мата найден в тексте

    # 2. ВТОРЫЙ ЭТАП: Подготовка текста для поштучной проверки одиночных слов
    cleaned_text = cleaned_text.replace('-', ' ').replace('/', ' ')
    cleaned_text = cleaned_text.translate(str.maketrans('', '', string.punctuation))
    words = cleaned_text.split()
    
    # 3. ТРЕТИЙ ЭТАП: Личный мини-список одиночных оскорблений
    my_custom_ban_list = {
        'чмо', 'чмоня', 'тварь', 'мразь', 'дебил', 'идиот', 'придурок', 'лохозавр',
    }
    
    # Проверяем каждое слово по датасету KartaSlovSent и по личному списку
    for word in words:
        if word in negative_words or word in my_custom_ban_list:
            return False  
            
    return True  # Текст полностью чистый


# 4. ТВОЯ ПОЛНАЯ КУЛИНАРНАЯ ИНСТРУКЦИЯ (SYSTEM PROMPT)
