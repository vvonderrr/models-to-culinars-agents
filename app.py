# 5. ФУНКЦИЯ ЗАПРОСА К МОДЕЛИ СО СТРИМИНГОМ
def ask_qwen_chef_stream(messages_history):
    """
    Принимает всю историю сообщений, отправляет её в LM Studio 
    и выводит ответ в терминал по буквам в реальном времени.
    Возвращает полный текст ответа для сохранения в историю.
    """
    try:
        # Отправляем запрос с параметром stream=True
        response_stream = client.chat.completions.create(
            model="*",  # Используем активную модель в LM Studio
            messages=messages_history,
            temperature=0.7,
            stream=True  # Включаем потоковую передачу данных
        )
        
        full_response = ""
        print("👨‍🍳 Помощник: ", end="", flush=True)
        
        # Читаем чанки (кусочки текста) по мере их поступления от сервера
        for chunk in response_stream:
            if chunk.choices and chunk.choices[0].delta.content:
                text_piece = chunk.choices[0].delta.content
                print(text_piece, end="", flush=True)  # Выводим кусочек без переноса строки
                full_response += text_piece            # Собираем полный ответ в строку
                
        print()  # Перенос строки в самом конце генерации
        return full_response

    except Exception as e:
        print(f"\n🍳 Ошибка подключения к LM Studio: {e}. Проверь, запущен ли Local Server!")
        return None

# 6. ИНТЕРФЕЙС ПРИЛОЖЕНИЯ В ТЕРМИНАЛЕ
print("=" * 60)
print("👨‍🍳 Приложение Кулинарный Помощник запущено!")
print("Связь с Qwen 3.5 восстановлена. Фильтр вежливости активен.")
print("Память диалога включена. Стриминг текста активен.")
print("=" * 60)

# Инициализируем историю сообщений и сразу закидываем туда системный промпт
history = [
    {"role": "system", "content": system_prompt}
]

while True:
    user_input = input("Пользователь: ")
    
    # Проверка на выход из приложения
    if user_input.lower() in ['выход', 'stop', 'стоп', 'exit']:
        print("\n👨‍🍳 Приятного аппетита! До новых встреч!")
        break
        
    if user_input.strip():
        # 1. Проверяем вежливость локально по файлу слов
        if not is_polite(user_input):
            print("👨‍🍳 Помощник: Извините, я не могу помочь с этим запросом. Пожалуйста, будьте вежливы.\n")
            continue  # Пропускаем отправку в модель, не засоряя историю грубостью
            
        # 2. Добавляем реплику пользователя в историю
        history.append({"role": "user", "content": user_input})
        
        # 3. Передаем ВСЮ историю в функцию и запускаем стриминг
        assistant_response = ask_qwen_chef_stream(history)
        
        # 4. Если ответ успешно получен, сохраняем его в историю для контекста следующих фраз
        if assistant_response:
            history.append({"role": "assistant", "content": assistant_response})
            
        print()  # Пустая строка для читаемости диалога
